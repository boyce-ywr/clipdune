import AppKit
import ClipDuneCore
import ImageIO
import UniformTypeIdentifiers

public enum PasteboardCodec {
    public static let supportedTypes: [NSPasteboard.PasteboardType] = [
        .string, .rtf, .html, .png, .tiff, .fileURL, .URL, .color, .pdf,
        NSPasteboard.PasteboardType("public.jpeg"), NSPasteboard.PasteboardType("com.compuserve.gif"),
        NSPasteboard.PasteboardType("public.heic")
    ]
    public static let generatedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    public static func read(_ pasteboard: NSPasteboard, sourceName: String, sourceBundleID: String,
                            excludedApplications: Set<String>, maximumBytes: Int = 16 * 1024 * 1024) throws -> ClipboardContent? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard CapturePolicy.allows(types: types, sourceBundleID: sourceBundleID,
                                   excludedApplications: excludedApplications, paused: false) else { return nil }
        guard let items = pasteboard.pasteboardItems, !items.isEmpty, items.count <= 100 else { return nil }
        let allTypes = Set(items.flatMap { $0.types.map(\.rawValue) })
        guard CapturePolicy.confidentialTypes.isDisjoint(with: allTypes) else { return nil }
        var fragments: [ClipboardFragment] = []
        var texts: [String] = []
        var bytes = 0
        var thumbnail: Data?
        var kinds: [ClipKind] = []
        for item in items {
            var representations: [ClipboardRepresentation] = []
            let types = supportedTypes.filter { item.types.contains($0) } + item.types.filter { !supportedTypes.contains($0) }
            for type in types where CapturePolicy.canStoreRepresentation(type.rawValue) {
                guard let data = item.data(forType: type) else { continue }
                bytes += data.count
                guard bytes <= maximumBytes else { throw HistoryError.invalidContent }
                representations.append(ClipboardRepresentation(type: type.rawValue, data: data))
                guard representations.count <= 32 else { throw HistoryError.invalidContent }
            }
            guard !representations.isEmpty else { return nil }
            fragments.append(ClipboardFragment(representations: representations))
            if let file = item.string(forType: .fileURL), let url = URL(string: file) {
                kinds.append(.files)
                texts.append(url.lastPathComponent)
            } else if let imageData = representations.first(where: { UTType($0.type)?.conforms(to: .image) == true })?.data {
                kinds.append(.image)
                if thumbnail == nil,
                   !imageData.isEmpty {
                    thumbnail = makeThumbnail(imageData)
                }
                if let text = item.string(forType: .string) { texts.append(text) }
            } else if item.types.contains(.color) {
                kinds.append(.color)
                if let color = NSColor(from: pasteboard)?.usingColorSpace(.sRGB) {
                    texts.append(String(format: "#%02X%02X%02X", Int((color.redComponent * 255).rounded()),
                                        Int((color.greenComponent * 255).rounded()), Int((color.blueComponent * 255).rounded())))
                }
            } else {
                let plain: String
                if let text = item.string(forType: .string) {
                    plain = text
                } else if let rich = item.data(forType: .rtf),
                          let attributed = NSAttributedString(rtf: rich, documentAttributes: nil) {
                    plain = attributed.string
                } else {
                    plain = item.string(forType: .URL) ?? item.string(forType: .html).map(plainTextFromHTML) ?? ""
                }
                texts.append(plain)
                if item.types.contains(.rtf) { kinds.append(.richText) }
                else if item.types.contains(.html) { kinds.append(.html) }
                else if let url = URL(string: plain), ["http", "https"].contains(url.scheme?.lowercased() ?? ""),
                        !plain.contains(where: \.isWhitespace) { kinds.append(.link) }
                else if colorFromHex(plain) != nil { kinds.append(.color) }
                else if item.types.contains(.string) { kinds.append(.text) }
                else { kinds.append(.other) }
            }
        }
        let text = texts.joined(separator: "\n")
        let priority: [ClipKind] = [.files, .image, .color, .richText, .html, .link, .text, .other]
        let kind = priority.first(where: kinds.contains) ?? .other
        return ClipboardContent(fragments: fragments, text: text, kind: kind,
                                sourceName: sourceName, sourceBundleID: sourceBundleID, thumbnail: thumbnail)
    }

    public static func colorFromHex(_ text: String) -> NSColor? {
        let value = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard value.hasPrefix("#"), [4, 7, 9].contains(value.count),
              value.dropFirst().allSatisfy({ $0.isHexDigit }) else { return nil }
        let hex = value.count == 4 ? value.dropFirst().map { "\($0)\($0)" }.joined() : String(value.dropFirst())
        guard let number = UInt64(hex, radix: 16) else { return nil }
        let hasAlpha = hex.count == 8
        let rgb = hasAlpha ? number >> 8 : number
        return NSColor(srgbRed: Double((rgb >> 16) & 255) / 255, green: Double((rgb >> 8) & 255) / 255,
                       blue: Double(rgb & 255) / 255, alpha: hasAlpha ? Double(number & 255) / 255 : 1)
    }

    private static func plainTextFromHTML(_ html: String) -> String {
        var text = html.replacingOccurrences(of: "(?is)<(script|style)\\b[^>]*>.*?</\\1\\s*>", with: "", options: .regularExpression)
        text = text.replacingOccurrences(of: "(?i)<(?:br\\s*/?|/p|/div|/li|/h[1-6])\\s*>", with: "\n", options: .regularExpression)
        text = text.replacingOccurrences(of: "<[^>]*>", with: "", options: .regularExpression)
        for (entity, replacement) in [("&nbsp;", " "), ("&lt;", "<"), ("&gt;", ">"), ("&quot;", "\""), ("&#39;", "'")] {
            text = text.replacingOccurrences(of: entity, with: replacement)
        }
        text = text.replacingOccurrences(of: "&amp;", with: "&")
        return text.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    @discardableResult
    public static func write(_ content: ClipboardContent, to pasteboard: NSPasteboard, plainText: Bool) -> Bool {
        let items: [NSPasteboardItem]
        if plainText {
            guard !content.text.isEmpty else { return false }
            let item = NSPasteboardItem()
            item.setString(content.text, forType: .string)
            item.setData(Data(), forType: generatedType)
            items = [item]
        } else {
            items = content.fragments.map { fragment in
                let item = NSPasteboardItem()
                for representation in fragment.representations {
                    item.setData(representation.data, forType: NSPasteboard.PasteboardType(representation.type))
                }
                if content.fragments.count == 1, [.text, .richText, .html, .link, .color].contains(content.kind),
                   !item.types.contains(.string), !content.text.isEmpty {
                    item.setString(content.text, forType: .string)
                }
                item.setData(Data(), forType: generatedType)
                return item
            }
        }
        pasteboard.clearContents()
        return pasteboard.writeObjects(items)
    }

    private static func makeThumbnail(_ data: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceThumbnailMaxPixelSize: 480,
                kCGImageSourceCreateThumbnailWithTransform: true
              ] as CFDictionary) else { return nil }
        return NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
    }
}
